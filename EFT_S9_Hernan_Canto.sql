--1.TABLA REGION
CREATE TABLE REGION (
ID_REGION       NUMBER(3)       NOT NULL,
NOMBRE_REGION   VARCHAR2(50)    NOT NULL,
CONSTRAINT REGION_PK PRIMARY KEY (ID_REGION)
);

--2.TABLA NACIONALIDAD
CREATE TABLE NACIONALIDAD (
ID_NACION       NUMBER(5) 
GENERATED ALWAYS AS IDENTITY (START WITH 210 INCREMENT BY 2) NOT NULL,
DESCRIPTION     VARCHAR2(30) NOT NULL,
CONSTRAINT NACIONALIDAD_PK PRIMARY KEY (ID_NACION) 
);

--3.TABLA ASOCIACION
CREATE TABLE ASOCIACION (
ID_ASOCIACION       NUMBER(5)       NOT NULL,
NOMBRE_ASOCIACION   VARCHAR2(60)    NOT NULL,
FECHA_CREACION      DATE            NOT NULL,
TIPO_ASOCIACION     CHAR(1)         NOT NULL,
CONSTRAINT ASOCIACION_PK PRIMARY KEY (ID_ASOCIACION),
CONSTRAINT ASOCIACION_FECHA_CK CHECK (FECHA_CREACION >= TO_DATE('31-12-1980',
'DD-MM-YY'))
);
---------------------------------------------------
--1. TABLA COMUNA (con clave foranea hacia REGION)
CREATE TABLE COMUNA (
ID_COMUNA       NUMBER(5)       NOT NULL,
ID_REGION       NUMBER(3)       NOT NULL,
NOMBRE_COMUNA   VARCHAR2(50)    NOT NULL,
CONSTRAINT COMUNA_PK PRIMARY KEY (ID_COMUNA),
CONSTRAINT COMUNA_REGION_FK FOREIGN KEY (ID_REGION) REFERENCES REGION 
(ID_REGION)
);

--2. LINEA DE SECUENCIA PARA CLUB_FUTBOL
CREATE SEQUENCE SEQ_CLUB_FUTBOL
START WITH 703
INCREMENT BY 4;

--3. LINEA TABLA CLUB_FUTBOL
CREATE TABLE CLUB_FUTBOL (
ID_CLUB             NUMBER(5)       NOT NULL,
NOMBRE_CLUB         VARCHAR2(60)    NOT NULL,
PATRIMONIO          NUMBER(12)      NOT NULL,
UBICACION_CALLE     VARCHAR2(100)   NOT NULL,
TIPO_CLUB           VARCHAR2(20)   DEFAULT 'Profesional' NOT NULL,
CONSTRAINT CLUB_FUTBOL_PK PRIMARY KEY (ID_CLUB),
CONSTRAINT CLUB_NOMBRE_UN UNIQUE (NOMBRE_CLUB)
);

--4. TABLA ESCUELA_FUTBOL
CREATE TABLE ESCUELA_FUTBOL (
ID_ESCUELA          NUMBER(5)       NOT NULL,
NOMBRE_ESCUELA      VARCHAR(60)     NOT NULL,
CAPACIDAD           NUMBER(5)       NOT NULL,
FECHA_FUNDACION     DATE            NOT NULL,
CONSTRAINT ESCUELA_FUTBOL_PK PRIMARY KEY (ID_ESCUELA)
);

--------------------------------------------------------

--1. TABLA IDIOMA
CREATE TABLE IDIOMA (
ID_IDIOMA       NUMBER(3)       NOT NULL,
NOMBRE_IDIOMA   VARCHAR2(30)    NOT NULL,
CONSTRAINT  IDIOMA_PK PRIMARY KEY (ID_IDIOMA)
);

--2. TABLA TRABAJADOR (supertuipo)
CREATE TABLE TRABAJADOR (
ID_TRABAJADOR       NUMBER(10)      NOT NULL,
RUT                 NUMBER(8)       NOT NULL,
DV                  CHAR(1)         NOT NULL,
NOMBRES             VARCHAR2(50)    NOT NULL,
APELLIDOS           VARCHAR2(50)    NOT NULL,
SUELDO_BASE         NUMBER(10)      NOT NULL,
FECHA_NACIMIENTO    DATE            NOT NULL,
GENERO              CHAR(1)         NOT NULL,
ESTADO_CIVIL        VARCHAR2(20)    NOT NULL,
TELEFONO            VARCHAR2(15),
DIRECCION           VARCHAR2(100)   NOT NULL,
ID_COMUNA           NUMBER(5)       NOT NULL,
ID_NACION           NUMBER(5)       NOT NULL,
CONSTRAINT TRABAJADOR_PK PRIMARY KEY (ID_TRABAJADOR),
CONSTRAINT TRABAJADOR_NACION_FK FOREIGN KEY (ID_NACION) REFERENCES NACIONALIDAD
(ID_NACION)
);

--3. TABLA JUGADOR (subtipo de trabajador)
CREATE TABLE JUGADOR (
ID_TRABAJADOR       NUMBER(10)       NOT NULL,
PUESTO              VARCHAR(30)      NOT NULL,
MONTO_PREMIOS       NUMBER(10)       NOT NULL,
ID_ASOCIACION       NUMBER(5)        NOT NULL,
ID_ESCUELA          NUMBER(5),
ANO_FIN_AMATEUR     NUMBER(4),
CONSTRAINT JUGADOR_PK PRIMARY KEY (ID_TRABAJADOR),
CONSTRAINT JUGADOR_TRABAJADOR_FK FOREIGN KEY (ID_TRABAJADOR)REFERENCES TRABAJADOR
(ID_TRABAJADOR),
CONSTRAINT JUGADOR_ASOCIACION_FK FOREIGN KEY (ID_ASOCIACION)REFERENCES ASOCIACION
(ID_ASOCIACION),
CONSTRAINT JUGADOR_ESCUELA_FK FOREIGN KEY (ID_ESCUELA)REFERENCES ESCUELA_FUTBOL
(ID_ESCUELA)
);

--4. TABLA PERSONAL PLANTA (subtipo trabajador)
CREATE TABLE PERSONAL_PLANTA(
ID_TRABAJADOR       NUMBER(5)       NOT NULL,
HORAS_TRABAJADAS    NUMBER(4),
VALOR_HORA_EXTRA    NUMBER(8),
CONSTRAINT PLANTA_PK PRIMARY KEY (ID_TRABAJADOR),
CONSTRAINT PLANTA_TRABAJADOR_FK FOREIGN KEY (ID_TRABAJADOR) REFERENCES TRABAJADOR
(ID_TRABAJADOR)
);

--5. TABLA JUGADOR IDIOMA(m:n)
CREATE TABLE JUGADOR_IDIOMA(
ID_TRABAJADOR       NUMBER(10)      NOT NULL,
ID_IDIOMA           NUMBER(3)       NOT NULL,
NIVEL_DOMINIO       VARCHAR2(20)    NOT NULL,
CONSTRAINT JUGADOR_IDIOMA_PK PRIMARY KEY (ID_TRABAJADOR, ID_IDIOMA),
CONSTRAINT JUG_IDIOMA_JUGADOR_FK FOREIGN KEY (ID_TRABAJADOR) REFERENCES JUGADOR
(ID_TRABAJADOR),
CONSTRAINT JUG_IDIOMA_IDIOMA_FK FOREIGN KEY (ID_IDIOMA) REFERENCES IDIOMA
(ID_IDIOMA)
);

--6. TABLA HISTORICO CLUB (Permanencia clubefs)
CREATE TABLE HISTORICO_CLUB (
ID_HISTORICO        NUMBER(8)       NOT NULL,
ID_TRABAJADOR       NUMBER(10)      NOT NULL,
ID_CLUB             NUMBER(5)       NOT NULL,
FECHA_INICIO        DATE            NOT NULL,
FECHA_FIN           DATE,
CONSTRAINT HISTORICO_CLUB_PK PRIMARY KEY (ID_HISTORICO),
CONSTRAINT HIS_CLUB_JUGADOR_FK FOREIGN KEY (ID_TRABAJADOR) REFERENCES JUGADOR
(ID_TRABAJADOR),
CONSTRAINT HIS_CLUB_CLUB_FK FOREIGN KEY (ID_CLUB) REFERENCES CLUB_FUTBOL (ID_CLUB) 
);

