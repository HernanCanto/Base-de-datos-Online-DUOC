--1. aciocioaciones de futbol profesional

SELECT
'ID:' || ID_ASOCIACION || ' * ' || NOMBRE_ASOCIACION AS ASOCIACION, TO_CHAR
(FECHA_CREACION,'DD-MM-YYYY')AS CREADA, TIPO_ASOCIACION AS TIPO
FROM ASOCIACION WHERE TIPO_ASOCIACION = 'P' AND FECHA_CREACION > TO_DATE
('31-12-2000', 'DD-MM-YYYY')ORDER BY FECHA_CREACION DESC;

--2. Patrimonio clubes de futbol clp y usd.

SELECT 
ID_CLUB AS "CLUB",
NOMBRE_CLUB AS "NOMBRE CLUB",
PATRIMONIO AS "PATRIMONIO EN PESOS",
PATRIMONIO / 955 AS "PATRIMONIO EN DOLARES"
FROM CLUB_FUTBOL
WHERE TIPO_CLUB = 'Profesional'
AND PATRIMONIO > 200000000
AND LOWER(NOMBRE_CLUB) LIKE '%a%' ORDER BY ID_CLUB DESC;









